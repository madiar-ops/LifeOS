import { MutationCache, QueryClient } from '@tanstack/react-query';

import { ApiError, describeError } from '@/types/errors';

import { toast } from './toastBus';

/**
 * Настройки кэша серверного состояния.
 *
 * ЗАЧЕМ TanStack Query, если MASTER_GUIDE называет Context API.
 * Context решает задачу «пробросить значение сквозь дерево компонентов» —
 * и для аутентификации и темы он в проекте и используется. Кэш серверных
 * данных — другая задача: устаревание, дедупликация одновременных запросов,
 * инвалидация после мутации, повтор при сетевом сбое, состояния loading/error.
 * Реализовать это на Context означает написать свой TanStack Query, только
 * без тестов. Требование документации не нарушено: Context остался на своём
 * месте, к нему добавлен инструмент для другой задачи.
 */
export const queryClient = new QueryClient({
  /**
   * Единый обработчик ошибок ВСЕХ мутаций.
   *
   * Иначе `onError` с показом уведомления дублировался бы в каждой из
   * нескольких десятков мутаций, и однажды его бы забыли — действие тихо
   * провалилось бы без объяснения.
   *
   * Ошибки валидации сюда не попадают намеренно: их место — под полями формы,
   * а не в углу экрана. Всплывающее «Проверь заполнение полей» рядом с уже
   * подсвеченным полем — это шум.
   */
  mutationCache: new MutationCache({
    onError: (error) => {
      if (error instanceof ApiError && error.isValidation) return;
      toast.error('Не удалось выполнить действие', describeError(error));
    },
  }),

  defaultOptions: {
    queries: {
      /**
       * Минута свежести. Переход между экранами не должен дёргать сервер
       * заново: данные дашборда за минуту не меняются, а мгновенная отрисовка
       * из кэша — это ровно то ощущение скорости, которое требует MASTER_GUIDE.
       */
      staleTime: 60_000,
      gcTime: 5 * 60_000,

      /**
       * Повтор ТОЛЬКО для сетевых сбоев и 5xx.
       *
       * Повторять 400/401/403/404 бессмысленно и вредно: ответ не изменится,
       * а пользователь три раза ждёт одну и ту же ошибку. Отдельно важно не
       * повторять 401 — обновлением токена занят перехватчик httpClient,
       * и дублирующий повтор мешал бы ему.
       */
      retry: (failureCount, error) => {
        if (failureCount >= 2) return false;
        if (error instanceof ApiError) {
          return error.status === 0 || error.status >= 500;
        }
        return false;
      },
      retryDelay: (attempt) => Math.min(1000 * 2 ** attempt, 8000),

      // Возврат на вкладку не должен провоцировать волну запросов.
      refetchOnWindowFocus: false,
      refetchOnReconnect: true,
    },
    mutations: {
      // Мутация — это действие пользователя. Автоматически повторять её нельзя:
      // повтор «создать транзакцию» создал бы вторую запись.
      retry: false,
    },
  },
});
