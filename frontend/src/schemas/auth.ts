import { z } from 'zod';

/**
 * Схемы форм аутентификации.
 *
 * Правила ЗЕРКАЛЯТ `RegisterRequestValidator` и `LoginRequestValidator` на
 * бэкенде. Это осознанное дублирование, а не недоверие к серверу:
 *
 *  - клиентская проверка нужна для мгновенной обратной связи — пользователь
 *    видит «нужна заглавная буква» до отправки, а не после круга по сети;
 *  - серверная проверка нужна для безопасности — запрос можно отправить и
 *    минуя интерфейс, поэтому сервер остаётся последней инстанцией и его
 *    правила НЕ ослабляются.
 *
 * Если правила разойдутся, пользователь увидит ошибку от сервера — она
 * прокидывается в форму через `setError`. То есть рассинхронизация деградирует
 * в чуть менее удобный интерфейс, а не в дыру в валидации.
 */

/** Требования к паролю из RegisterRequestValidator (8..128, A-Z, a-z, 0-9). */
export const passwordSchema = z
  .string()
  .min(8, 'Пароль не короче 8 символов.')
  .max(128, 'Пароль не длиннее 128 символов.')
  .regex(/[A-Z]/, 'Нужна хотя бы одна заглавная буква.')
  .regex(/[a-z]/, 'Нужна хотя бы одна строчная буква.')
  .regex(/[0-9]/, 'Нужна хотя бы одна цифра.');

export const loginSchema = z.object({
  email: z.string().min(1, 'Email обязателен.').email('Некорректный формат email.'),
  // На входе пароль НЕ проверяется по сложности: правила могли измениться
  // после регистрации, и «пароль слишком простой» на форме входа — абсурд.
  password: z.string().min(1, 'Пароль обязателен.'),
});

export const registerSchema = z.object({
  name: z.string().min(1, 'Имя обязательно.').max(100, 'Имя не длиннее 100 символов.'),
  surname: z.string().min(1, 'Фамилия обязательна.').max(100, 'Фамилия не длиннее 100 символов.'),
  email: z
    .string()
    .min(1, 'Email обязателен.')
    .email('Некорректный формат email.')
    .max(256, 'Email не длиннее 256 символов.'),
  password: passwordSchema,
});

export type LoginFormValues = z.infer<typeof loginSchema>;
export type RegisterFormValues = z.infer<typeof registerSchema>;
